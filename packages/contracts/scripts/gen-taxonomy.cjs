#!/usr/bin/env node
// Generates src/taxonomy.ts from benchmark/schema/classes.json (Data/QA owns the taxonomy).
// Run: pnpm --filter @kamutan/contracts gen:taxonomy   (test/taxonomy.test.ts fails when it drifts)
const fs = require('node:fs');
const path = require('node:path');

const src = path.join(__dirname, '..', '..', '..', 'benchmark', 'schema', 'classes.json');
const out = path.join(__dirname, '..', 'src', 'taxonomy.ts');
const json = JSON.parse(fs.readFileSync(src, 'utf8'));
// "unknown" (if present in the JSON) is the reserved detection class for unrecognised symbols: it is never an
// assignable class, so it is excluded from SYMBOL_CLASSES and covered by UNKNOWN_CLASS / DetectionClassSchema.
const entries = Object.entries(json.classes).filter(([id]) => id !== 'unknown');
for (const [id] of entries) {
  if (!/^[a-z][a-z0-9_]{0,63}$/.test(id)) throw new Error(`invalid class id ${id}`);
}
const q = (s) => JSON.stringify(s);
const lines = [
  '// GENERATED by scripts/gen-taxonomy.cjs from benchmark/schema/classes.json — do not edit by hand.',
  `// schema_version ${json.schema_version}; test/taxonomy.test.ts fails when this file drifts from the JSON.`,
  "import { z } from 'zod';",
  '',
  `export const TAXONOMY_SCHEMA_VERSION = ${q(json.schema_version)};`,
  '',
  '/** Class ids of the MVP taxonomy (benchmark/schema/classes.json), in file order, without the reserved "unknown". */',
  'export const SYMBOL_CLASSES = [',
  ...entries.map(([id]) => `  ${q(id)},`),
  '] as const;',
  '',
  'export type SymbolClass = (typeof SYMBOL_CLASSES)[number];',
  '',
  'export interface SymbolClassInfo {',
  '  domain: string;',
  '  core: boolean;',
  '  /** Hebrew display label. */',
  '  he: string;',
  '}',
  '',
  'export const SYMBOL_CLASS_INFO: Readonly<Record<SymbolClass, SymbolClassInfo>> = Object.freeze({',
  ...entries.map(([id, c]) => `  ${id}: { domain: ${q(c.domain)}, core: ${Boolean(c.core)}, he: ${q(c.he)} },`),
  '});',
  '',
  '/** A class a user may assign (confirm / reassign / resolve). Never "unknown". */',
  'export const SymbolClassSchema = z.enum(SYMBOL_CLASSES);',
  '',
  '/** Reserved class of detections whose symbol is not recognised (always with a clusterId). */',
  "export const UNKNOWN_CLASS = 'unknown' as const;",
  '',
  '/** Class written by the worker on detections / legend suggestions: a taxonomy id or "unknown". */',
  'export const DetectionClassSchema = z.enum([...SYMBOL_CLASSES, UNKNOWN_CLASS]);',
  'export type DetectionClass = z.infer<typeof DetectionClassSchema>;',
  '',
];
fs.writeFileSync(out, lines.join('\n'));
console.log(`wrote ${entries.length} classes to ${path.relative(process.cwd(), out)}`);
