# Latin lowercase falls back to the capital (CAD stroke fonts often look like this at small sizes).
FALLBACK: dict[str, str] = {c: c.upper() for c in "abcdefghijklmnopqrstuvwxyz"}
FALLBACK.update({"״": '"', "׳": "'", "–": "-", "Φ": "Ø", "ø": "Ø", "Q": "O", "q": "O"})


def glyph(ch: str) -> Glyph:
    g = GLYPHS.get(ch)
    if g is None:
        g = GLYPHS.get(FALLBACK.get(ch, ""), GLYPHS["*"])
    return g


def advance(text: str) -> float:
    """Width of a (visual-order) string in cap-height units, with 0.08 letter spacing."""
    if not text:
        return 0.0
    return sum(glyph(c)[0] for c in text) + 0.08 * (len(text) - 1)
