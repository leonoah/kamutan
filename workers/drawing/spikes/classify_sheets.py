"""Title block + discipline/floor/scale for all sample sheets -> SHEET_CLASSIFICATION.md.

Run after `shx_spike.py extract label`:
    uv run python spikes/classify_sheets.py
Uses only the vector glyph dictionary (no VLM). Compares with the data agent's
manifest (benchmark/manifests/noah.json) when present.
"""

from __future__ import annotations

import json
import pickle
import sys
from dataclasses import asdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import shx_spike as S

from kamutan_drawing.ingest.pdf_vector import extract_pdf
from kamutan_drawing.ocr.dictionary import text_spans
from kamutan_drawing.scale.detect import detect_scale
from kamutan_drawing.titleblock.classify import DISCIPLINES, FLOORS, classify_sheet, read_title_block

MANIFEST = Path(__file__).resolve().parents[3] / "benchmark" / "manifests" / "noah.json"
# manifest uses "master" for the architectural master plan
CODE_MAP = {"architecture_master": "master"}


def main() -> None:
    lines = S.load_lines()
    # spike-local cache written by this script, never untrusted input
    gd = pickle.load(open(S.OUT / "gd.pkl", "rb"))  # nosemgrep
    gd.assign(lines)
    manifest = {}
    if MANIFEST.exists():
        for f in json.loads(MANIFEST.read_text())["files"]:
            if f.get("kind") == "pdf":
                manifest[f["file_id"].replace("sheet_", "")] = f
    rows, out_json = [], {}
    for f in S.sheet_files():
        sid = S.sid_of(f)
        vs = extract_pdf(f)[0]
        sl = [ln for ln in lines if ln.sheet == sid]
        spans = text_spans(sl, gd)
        tb = read_title_block(spans, vs)
        cl = classify_sheet(tb)
        sc = detect_scale(cl.scale_den, spans, vs)
        out_json[sid] = {"title_block": asdict(tb), "class": asdict(cl), "scale": asdict(sc)}
        man = manifest.get(sid, {})
        mdisc = man.get("discipline")
        mfl = man.get("floors", [])
        mydisc = [CODE_MAP.get(d, d) for d in cl.disciplines]
        agree_d = (mdisc in mydisc) if mdisc else None
        agree_f = (sorted(mfl) == sorted(cl.floors)) if mfl else None
        rows.append((sid, cl, sc, tb, mdisc, mfl, agree_d, agree_f))
        print(
            sid, cl.disciplines, cl.floors, cl.scale_den, cl.confidence, sc.from_dimensions, sc.n_dimension_pairs, "|", cl.title
        )
    (S.HERE / "results").mkdir(exist_ok=True)
    (S.OUT / "sheet_classification.json").write_text(json.dumps(out_json, ensure_ascii=False, indent=1, default=str))

    heb_d = {k: v[0] for k, v in DISCIPLINES.items()}
    heb_f = {k: v[0] for k, v in FLOORS.items()}
    md = [
        "# Sheet classification — sample project (15 sheets)",
        "",
        "Generated by `spikes/classify_sheets.py` from the **vector glyph dictionary only** (no VLM, no raster OCR at read time).",
        'Discipline/floor come from the title block field *שם הגיליון*; scale from *קנ"מ*; `dim scale` = independent estimate',
        "from dimension strings (number above a parallel dimension line, value in cm). `conf` = keyword match x OCR confidence.",
        "Manifest = `benchmark/manifests/noah.json` (data agent).",
        "",
        "| file id | sheet name (as read) | discipline | floor(s) | scale | dim scale (pairs) | date | conf | manifest | agrees |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for sid, cl, sc, tb, mdisc, mfl, ad, af in rows:
        disc = ", ".join(f"{heb_d[d]} (`{d}`)" for d in cl.disciplines) or "?"
        fl = ", ".join(f"{heb_f[x]} (`{x}`)" for x in cl.floors) or "?"
        dims = f"1:{sc.from_dimensions} ({sc.n_dimension_pairs})" if sc.from_dimensions else f"- ({sc.n_dimension_pairs})"
        man = f"{mdisc} / {', '.join(mfl)}" if mdisc else "-"
        agree = "-" if ad is None else ("yes" if ad and af else ("discipline only" if ad else ("floor only" if af else "NO")))
        md.append(
            f"| sheet_{sid} | {cl.title} | {disc} | {fl} | 1:{cl.scale_den} | {dims} | {cl.date or '?'} | {cl.confidence:.2f} | {man} | {agree} |"
        )
    md += [
        "",
        "## Notes",
        "",
        "- Every title block declares 1:50 and date 22.12.16; the title-block text is read correctly on all 15 sheets after the",
        "  geometric label vetoes (see SHX_SPIKE_REPORT.md).",
        "- **Disagreement with the manifest on floors** for `sheet_1bbe4113` (lighting), `sheet_c054fd3a` (electrical) and",
        "  `sheet_6fa88f92` (master): the title block literally says *קומת מרתף+ / קומת קרקע*, while the manifest says",
        "  basement + **first**. The lower plan on these portrait sheets shows bedrooms (שינה 1-3, סוויטת הורים), i.e. the upper",
        "  storey, so the manifest is probably right about the content and the title block wording is the office's naming",
        "  (split-level house: entrance level = 'קרקע'?). Needs a human answer; until then the product must let the user",
        "  confirm floor per *region* (decision table #10, `sheet_regions`).",
        "- Discipline agrees with the manifest on all sheets (`architecture_master` = manifest `master`).",
    ]
    (S.HERE / "SHEET_CLASSIFICATION.md").write_text("\n".join(md) + "\n")
    print("wrote", S.HERE / "SHEET_CLASSIFICATION.md")


if __name__ == "__main__":
    main()
